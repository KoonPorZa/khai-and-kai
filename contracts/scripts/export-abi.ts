import fs from "node:fs";
import path from "node:path";
import hre from "hardhat";

/** Writes typed ABIs and deployments for the web app into web/src/abi/. */
async function main() {
  const outDir = path.join(__dirname, "..", "..", "web", "src", "abi");
  fs.mkdirSync(outDir, { recursive: true });
  const targets: [string, string, string][] = [
    ["Khai", "khaiAbi", "khai.ts"],
    ["Kai", "kaiAbi", "kai.ts"],
    ["KaiRenderer", "rendererAbi", "renderer.ts"],
  ];
  for (const [contract, exportName, file] of targets) {
    const { abi } = await hre.artifacts.readArtifact(contract);
    const body = `// Generated by contracts/scripts/export-abi.ts. Do not edit.\nexport const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`;
    fs.writeFileSync(path.join(outDir, file), body);
    console.log(`  wrote web/src/abi/${file}`);
  }
  const depDir = path.join(__dirname, "..", "deployments");
  const merged: Record<string, unknown> = {};
  if (fs.existsSync(depDir)) {
    for (const f of fs.readdirSync(depDir).filter((f) => /^\d+\.json$/.test(f))) {
      merged[f.replace(".json", "")] = JSON.parse(fs.readFileSync(path.join(depDir, f), "utf8"));
    }
  }
  fs.writeFileSync(path.join(outDir, "deployments.json"), JSON.stringify(merged, null, 2) + "\n");
  console.log(`  wrote web/src/abi/deployments.json (chains: ${Object.keys(merged).join(", ") || "none"})`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exitCode = 1;
});
